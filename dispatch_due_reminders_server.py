"""
Composed workflow to find due events, personalize messages, translate to
preferred language, generate speech audio, and dispatch with timestamps when
confirm=true. Skips already-dispatched events.

Generated by Synapse (v2 Custom mode). The FastMCP scaffold, scan, and tool
registration are Synapse's; the tool body was reviewed after generation and
tightened into a thin pass-through of the composed workflow in
notifier.services.reminder_dispatch (this file is ours to edit, per Synapse).

Run:  python dispatch_due_reminders_server.py
"""
from __future__ import annotations

from mcp.server.fastmcp import FastMCP

from notifier.services.reminder_dispatch import dispatch_due_reminders

mcp = FastMCP("dispatch_due_reminders")


@mcp.tool(
    name="dispatch_due_reminders",
    description=(
        "Composed workflow to find due reminder events, personalize each message, "
        "translate it into each person's preferred language, and generate voice "
        "audio. confirm=false previews drafts and changes nothing; confirm=true "
        "records dispatch timestamps and skips already-dispatched events. Pass "
        "event_ids (list of integers) to scope the run to specific events."
    ),
)
def dispatch_due_reminders_tool(confirm: bool = False, event_ids: list[int] | None = None) -> dict:
    """Preview (confirm=false) or dispatch (confirm=true) due reminders."""
    if not isinstance(confirm, bool):
        return {"error": "confirm must be a bool"}
    if event_ids is not None and not isinstance(event_ids, list):
        return {"error": "event_ids must be a list of integers"}
    return dispatch_due_reminders(confirm=confirm, event_ids=event_ids)


if __name__ == "__main__":
    mcp.run()
